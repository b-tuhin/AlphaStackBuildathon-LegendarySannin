// Merge extra keys into every language; English only fills keys missing everywhere.
for (const code of Object.keys(STRINGS)) {
  for (const extra of [extraA, terms1, terms2]) {
    const own = extra[code] || {};
    const fill = {};
    for (const k of Object.keys(extra.en || {})) {
      if (!(k in own) && !(k in STRINGS[code])) fill[k] = extra.en[k];
    }
    STRINGS[code] = { ...fill, ...STRINGS[code], ...own };
  }
}

